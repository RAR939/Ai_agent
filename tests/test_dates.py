def test_enough_cases():
    assert len(CASES) >= 50


@pytest.mark.parametrize("text,base,disc,expected", CASES,
                         ids=[f"{i:02d}-{c[0][:28]}" for i, c in enumerate(CASES)])
def test_resolve_due(text, base, disc, expected):
    got, fuzzy = dates.resolve_due(text, base, disc)
    assert got == expected
    assert fuzzy is (expected is None)


@pytest.mark.parametrize("text,base,disc,expected", KNOWN_FAILURES)
@pytest.mark.xfail(reason="известное ограничение, см. docs/tracker_notes.md", strict=True)
def test_known_failures(text, base, disc, expected):
    assert dates.resolve_due(text, base, disc) == (expected, False)


def test_result_is_valid_contract_time():
    from src.schemas import check_iso_msk
    for text, base, disc, expected in CASES:
        got, _ = dates.resolve_due(text, base, disc)
        assert check_iso_msk(got) == got


def test_message_in_other_timezone_is_converted():
    # 21:30 UTC в понедельник = 00:30 вторника по Москве: «в пятницу» считается от вторника
    got, _ = dates.resolve_due("в пятницу", "2026-10-19T21:30:00+00:00")
    assert got == "2026-10-23T23:59:00+03:00"


def test_relative_base_is_message_not_today():
    a, _ = dates.resolve_due("завтра", "2025-01-10T10:00:00+03:00")
    assert a == "2025-01-11T23:59:00+03:00"
